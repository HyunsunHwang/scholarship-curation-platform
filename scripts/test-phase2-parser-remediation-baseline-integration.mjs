import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadNoticeSourceManifestRegistry } from "../lib/notice-source-manifest-loader.mjs";
import { buildPhase2BaselineArtifacts } from "./build-phase2-parser-remediation-baseline.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const REPORTS = path.join(ROOT, "reports", "runtime-diagnostics");
const PHASE2 = path.join(REPORTS, "phase2-parser-remediation");
const historicalReport = JSON.parse(fs.readFileSync(path.join(REPORTS, "verified-source-parser-remediation-2026-07-25.json"), "utf8"));
const snapshot = JSON.parse(fs.readFileSync(path.join(PHASE2, "runtime-input-snapshot.json"), "utf8"));
const registry = loadNoticeSourceManifestRegistry({ includeDisabled: true });
const artifacts = buildPhase2BaselineArtifacts({ historicalReport, runtimeReport: snapshot });
const canonical = (value) => `${JSON.stringify(value, null, 2)}\n`;

assert.equal(registry.sources.length, 545);
assert.equal(snapshot.source_registry.sourceCount, 545);
assert.equal(snapshot.run_at, "2026-07-27T08:01:04.472Z");
assert.equal(historicalReport.target_definition, "pre-remediation LIST_SELECTOR_MENU_CONTAMINATION with heuristic_anchor");
assert.equal(historicalReport.inventory.length, 87);
const targetIds = historicalReport.inventory.map((item) => item.source_id);
assert.equal(new Set(targetIds).size, 87);
assert.ok(historicalReport.inventory.every((item) => item.parser_strategy_before === "heuristic_anchor"));
const manifestIds = new Set(registry.sources.map((source) => source.sourceId));
assert.ok(targetIds.every((sourceId) => manifestIds.has(sourceId)));
assert.equal(snapshot.source_diagnostics.length, 87);
const diagnosticsById = new Map(snapshot.source_diagnostics.map((diagnostic) => [diagnostic.source_id, diagnostic]));
assert.equal(diagnosticsById.size, 87);
assert.ok(targetIds.every((sourceId) => diagnosticsById.has(sourceId)));
assert.equal(snapshot.provenance.runtime_report_sha256, "13c5feba99182c96da48d075d57aad207d436a912bdbd724163c8b29c1fc2801");
assert.equal(snapshot.provenance.tested_code_base_sha, "b9bf5002703e0e131bade45a88f561bb46cb389a");
assert.equal(snapshot.provenance.original_runtime_report_path, ".tmp/runtime-analysis/main-post-merge-20260727/scholarship-notices-latest.json");
const second = buildPhase2BaselineArtifacts({ historicalReport, runtimeReport: snapshot });
assert.deepEqual(second, artifacts);
assert.equal(canonical(artifacts.targetSources), fs.readFileSync(path.join(PHASE2, "target-sources.json"), "utf8"));
assert.equal(canonical(artifacts.baseline), fs.readFileSync(path.join(PHASE2, "baseline.json"), "utf8"));
assert.equal(artifacts.markdown, fs.readFileSync(path.join(PHASE2, "baseline.md"), "utf8"));
console.log("phase2_parser_remediation_baseline_integration_tests_passed=13");
